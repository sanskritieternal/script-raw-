"""Read and inventory every repository file; validate the generated topic grid.

Run: python -m Tools.validation.audit_repository
This is read-only except for the two reports in AUDIT/.
"""
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "AUDIT"
SKIP = {".git", "__pycache__", "AUDIT"}


def fingerprint(path):
    data = path.read_bytes()
    return len(data), sha256(data).hexdigest()


def main():
    OUT.mkdir(exist_ok=True)
    listed = subprocess.check_output(["rg", "--files", "--hidden", "-g", "!.git", "-g", "!AUDIT"], cwd=ROOT, text=True)
    files = sorted((ROOT / rel for rel in listed.splitlines() if rel and not any(part in SKIP for part in Path(rel).parts)), key=lambda p: str(p).lower())
    counts = Counter()
    manifest = ["# File verification inventory", "", "Generated by `python -m Tools.validation.audit_repository`. A checkmark means the complete file bytes were read and hashed; it does **not** mean a human reviewed every sentence or verified factual claims. The generated `AUDIT/` reports and Python cache are excluded to prevent self-referential hashes.", "", "| Read | File | Bytes | SHA-256 |", "|---|---|---:|---|"]
    with ThreadPoolExecutor(max_workers=8) as pool:
        for number, (p, (size, digest)) in enumerate(zip(files, pool.map(fingerprint, files)), 1):
            rel = p.relative_to(ROOT).as_posix()
            counts[rel.split("/")[0]] += 1
            manifest.append(f"| ✓ | `{rel}` | {size} | `{digest}` |")
            if number % 5000 == 0:
                print(f"Read and hashed {number}/{len(files)} files", flush=True)
    (OUT / "FILE_VERIFICATION.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print(f"Read and hashed {len(files)} files; checking registry and scope gates", flush=True)

    topic_root = ROOT / "REGISTRY" / "Niches"
    dirs = sorted(p for p in topic_root.glob("*/Angles") if p.is_dir())
    import csv
    from Tools.registry.populate_niches import angle_entries, parse_master_registry
    with (ROOT / "REGISTRY" / "NICHE_TAXONOMY.csv").open(encoding="utf-8", newline="") as fh:
        rows = {int(row["id"]): row for row in csv.DictReader(fh)}
    category_counts = Counter(row["primary_category"] for row in rows.values())
    master = {n: angles for n, _, angles in parse_master_registry()}
    missing = []
    mismatched = []
    for d in dirs:
        ids = set()
        found = set()
        for p in d.glob("[0-9][0-9][0-9]_*.md"):
            m = re.match(re.escape(d.parent.name) + r"_(.+)\.md$", p.name)
            if m:
                ids.add(d.parent.name[:3])
                found.add(m.group(1))
            else:
                mismatched.append(p.relative_to(ROOT).as_posix())
        niche_id = int(d.parent.name[:3])
        expected = {entry["slug"] for entry in angle_entries(rows[niche_id], master[niche_id])}
        if len(ids) != 1 or found != expected or not (d / "ALL_TOPICS_BY_NICHE.md").exists():
            missing.append((d.relative_to(ROOT).as_posix(), sorted(expected - found), sorted(found - expected), sorted(ids)))
    report = ["# Automated structural audit", "", f"Files read and hashed: **{len(files)}**. Topic directories: **{len(dirs)}**.", "", "## Files by root", ""]
    report += [f"- {k}: {v}" for k, v in sorted(counts.items())]
    report += ["", "## Topic folders by current category", ""]
    report += [f"- {k}: {v}" for k, v in sorted(category_counts.items())]
    report += ["", f"Incomplete topic grids: **{len(missing)}**. Misnamed topic files: **{len(mismatched)}**.", ""]
    report += [f"- `{d}` missing={mi} extra={ex} ids={ids}" for d, mi, ex, ids in missing[:100]]
    report += [f"- Misnamed: `{x}`" for x in mismatched[:100]]
    report += ["", "This verifies file presence and naming only. It does not establish source quality, topic distinctness, or correct category assignment."]
    schema_check = subprocess.run([sys.executable, "-m", "Tools.validation.validate_repository"], cwd=ROOT, text=True, capture_output=True)
    report += ["", "## Schema and Phase 0 pilot validation", "", f"Exit code: **{schema_check.returncode}**.", "", "```text", (schema_check.stdout + schema_check.stderr).strip(), "```", ""]
    generator_check = subprocess.run([sys.executable, "-m", "Tools.registry.populate_niches", "--verify-content"], cwd=ROOT, text=True, capture_output=True)
    report += ["### Generated content reproducibility", "", f"Exit code: **{generator_check.returncode}**.", "", "```text", (generator_check.stdout + generator_check.stderr).strip(), "```", ""]
    scope_check = subprocess.run([sys.executable, "-m", "Tools.registry.review_angle_plans", "--scope-audit"], cwd=ROOT, text=True, capture_output=True)
    report += ["### Angle scope context", "", f"Exit code: **{scope_check.returncode}**.", "", "```text", (scope_check.stdout + scope_check.stderr).strip(), "```", ""]
    pilots = [
        ("Full six-phase text pilot", ROOT / "AUDIT" / "PILOTS" / "343_physics" / "343_physics_beginner_explainers_si_light_speed_exact", "5"),
        ("Variable-duration Phase 0 pilot", ROOT / "AUDIT" / "PILOTS" / "343_physics" / "343_physics_advanced_concepts_metre_light_second", "0"),
    ]
    pilot_failed = False
    for label, path, phase in pilots:
        result = subprocess.run([sys.executable, "-m", "Tools.validation.validate_project", str(path), "--through", phase], cwd=ROOT, text=True, capture_output=True)
        report += [f"### {label}", "", f"Exit code: **{result.returncode}**.", "", "```text", (result.stdout + result.stderr).strip(), "```", ""]
        pilot_failed |= result.returncode != 0
    gate_tests = subprocess.run([sys.executable, "-m", "unittest", "tests.test_contract", "tests.test_production_workflow", "tests.test_idea_bank", "tests.test_depth_planning", "-v"], cwd=ROOT, text=True, capture_output=True)
    report += ["### Blocker and timing tests", "", f"Exit code: **{gate_tests.returncode}**.", "", "```text", (gate_tests.stdout + gate_tests.stderr).strip(), "```", ""]
    (OUT / "STRUCTURAL_AUDIT.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"Read {len(files)} files; {len(dirs)} topic directories; {len(missing)} incomplete grids; {len(mismatched)} misnamed files")
    if schema_check.returncode or generator_check.returncode or scope_check.returncode or pilot_failed or gate_tests.returncode:
        raise SystemExit(schema_check.returncode or generator_check.returncode or scope_check.returncode or gate_tests.returncode or 1)


if __name__ == "__main__":
    main()
